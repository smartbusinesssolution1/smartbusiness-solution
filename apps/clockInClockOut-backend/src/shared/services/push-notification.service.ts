import { memoryCache } from "./cache.service.js";
import { logger } from "./logger.js";

export interface SendPushNotificationOptions {
  userId?: string;
  employeeId?: string;
  token?: string;
  title: string;
  body: string;
  data?: Record<string, any>;
  sound?: string;
  badge?: number;
}

export interface PushNotificationResult {
  success: boolean;
  simulated?: boolean;
  error?: string;
  ticketId?: string;
}

/**
 * Service to manage Expo Push Notification tokens and send alerts to employee mobile devices.
 */
export class PushNotificationService {
  private static readonly TOKEN_TTL_SECONDS = 30 * 24 * 60 * 60; // 30 days
  private static readonly EXPO_PUSH_URL = "https://exp.host/--/api/v2/push/send";

  /**
   * Associates and persists an Expo push token with a user ID and optional employee ID.
   */
  async savePushToken(userId: string, token: string, employeeId?: string): Promise<void> {
    if (!token || typeof token !== "string") {
      return;
    }

    const trimmed = token.trim();
    memoryCache.set(`push_token:user:${userId}`, trimmed, PushNotificationService.TOKEN_TTL_SECONDS);

    if (employeeId) {
      memoryCache.set(`push_token:emp:${employeeId}`, trimmed, PushNotificationService.TOKEN_TTL_SECONDS);
    }

    logger.info(
      {
        userId,
        employeeId,
        tokenPrefix: trimmed.slice(0, 20) + "...",
      },
      "Push token successfully saved to cache"
    );
  }

  /**
   * Retrieves the stored push token for a given user ID.
   */
  async getPushToken(userId: string): Promise<string | undefined> {
    return memoryCache.getAsync<string>(`push_token:user:${userId}`);
  }

  /**
   * Retrieves the stored push token for a given employee profile ID.
   */
  async getPushTokenByEmployeeId(employeeId: string): Promise<string | undefined> {
    return memoryCache.getAsync<string>(`push_token:emp:${employeeId}`);
  }

  /**
   * Removes push tokens associated with the user/employee upon logout or deregistration.
   */
  async removePushToken(userId: string, employeeId?: string): Promise<void> {
    memoryCache.delete(`push_token:user:${userId}`);
    if (employeeId) {
      memoryCache.delete(`push_token:emp:${employeeId}`);
    }
  }

  /**
   * Dispatches a push notification via Expo Push Notification service.
   * Handles simulated tokens cleanly and never throws uncaught exceptions that break caller flows.
   */
  async sendPushNotification(options: SendPushNotificationOptions): Promise<PushNotificationResult> {
    try {
      let recipientToken = options.token;

      if (!recipientToken && options.userId) {
        recipientToken = await this.getPushToken(options.userId);
      }

      if (!recipientToken && options.employeeId) {
        recipientToken = await this.getPushTokenByEmployeeId(options.employeeId);
      }

      if (!recipientToken) {
        logger.debug(
          { userId: options.userId, employeeId: options.employeeId },
          "No push token registered for recipient; skipping push notification"
        );
        return {
          success: false,
          error: "No push token registered",
        };
      }

      // Check if this is a simulated/development token generated by mobile client in emulator/test environment
      const isSimulatedDevToken =
        recipientToken.includes("dev_") ||
        recipientToken.startsWith("ExponentPushToken[dev_") ||
        recipientToken.startsWith("token_");

      if (isSimulatedDevToken) {
        logger.info(
          {
            token: recipientToken,
            title: options.title,
            body: options.body,
            data: options.data,
          },
          "Simulated push notification dispatched to development device"
        );
        return {
          success: true,
          simulated: true,
        };
      }

      // Validate standard Expo push token format
      const isValidExpoToken =
        recipientToken.startsWith("ExponentPushToken[") ||
        recipientToken.startsWith("ExpoPushToken[") ||
        /^[a-zA-Z0-9_-]{22}$/.test(recipientToken);

      if (!isValidExpoToken) {
        logger.warn(
          { token: recipientToken },
          "Invalid push token format; skipping Expo push send"
        );
        return {
          success: false,
          error: "Invalid push token format",
        };
      }

      const payload = {
        to: recipientToken,
        sound: options.sound ?? "default",
        title: options.title,
        body: options.body,
        badge: options.badge,
        data: options.data ?? {},
        channelId: "leaves",
      };

      const response = await fetch(PushNotificationService.EXPO_PUSH_URL, {
        method: "POST",
        headers: {
          Accept: "application/json",
          "Accept-Encoding": "gzip, deflate",
          "Content-Type": "application/json",
        },
        body: JSON.stringify(payload),
      });

      if (!response.ok) {
        const errorText = await response.text();
        logger.warn(
          { status: response.status, errorText },
          "Expo push notification service returned error HTTP status"
        );
        return {
          success: false,
          error: `HTTP ${response.status}: ${errorText}`,
        };
      }

      const resJson = (await response.json()) as any;
      const ticket = resJson?.data;

      logger.info(
        {
          ticket,
          title: options.title,
          tokenPrefix: recipientToken.slice(0, 15) + "...",
        },
        "Push notification successfully sent via Expo push service"
      );

      return {
        success: true,
        ticketId: Array.isArray(ticket) ? ticket[0]?.id : ticket?.id,
      };
    } catch (err: any) {
      logger.warn(
        { err: err?.message, title: options.title },
        "Unexpected error occurred while dispatching push notification"
      );
      return {
        success: false,
        error: err?.message,
      };
    }
  }
}

export const pushNotificationService = new PushNotificationService();
